import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const manifestUrl = new URL("../../deployments/robinhood-chain-4663.json", import.meta.url);
const outputUrl = new URL("../src/generated/robinhoodChain.ts", import.meta.url);
const manifest = JSON.parse(readFileSync(manifestUrl, "utf8"));

const contract = (name) => {
  const configured = manifest.contracts[name];
  if (!configured?.address) throw new Error(`missing ${name} address in Robinhood manifest`);
  return {
    address: configured.address,
    ...(configured.runtimeCodeHash ? { runtimeCodeHash: configured.runtimeCodeHash } : {}),
  };
};

const generated = `// Generated by sdk/scripts/generate-robinhood-config.mjs.
// Source: deployments/robinhood-chain-4663.json. Do not edit by hand.
export const robinhoodChain = ${JSON.stringify({
  network: manifest.network,
  chainId: manifest.chainId,
  forkBlock: manifest.forkBlock,
  forkBlockHash: manifest.forkBlockHash,
  hookFeeBps: manifest.staticsLiquidityCalibration.hookFeeBps,
  hookPermissionMask: manifest.staticsLiquidityCalibration.hookPermissionMask,
  liquidityCalibration: manifest.staticsLiquidityCalibration,
  contracts: {
    poolManager: contract("poolManager"),
    positionManager: contract("positionManager"),
    quoter: contract("quoter"),
    stateView: contract("stateView"),
    universalRouter: contract("universalRouter"),
    permit2: contract("permit2"),
    weth: contract("weth"),
  },
}, null, 2)} as const;
`;

writeFileSync(fileURLToPath(outputUrl), generated);
